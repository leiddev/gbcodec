#!/usr/bin/env python3
"""Generate the GB2312 <-> Unicode conversion tables.

The canonical mapping comes from Python's built-in ``gb2312`` codec, which
implements GB2312-80 (6763 hanzi + 682 symbols = 7445 characters). The
resulting tables are checked in so that building the library never depends on
Python.

Two tables are produced:

* ``gbc_detail_gb2312_index``: a flat, directly indexable array indexed by
  ``(lead - 0xA1) * 94 + (trail - 0xA1)``. 0 marks an unassigned code.
* ``gbc_detail_code_point_order``: the same mapping sorted by Unicode code
  point, used for binary search.

Usage:
    python3 tools/gen_gb2312_table.py            # rewrite the generated file
    python3 tools/gen_gb2312_table.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

FIRST_LEAD = 0xA1
LAST_LEAD = 0xF7
FIRST_TRAIL = 0xA1
LAST_TRAIL = 0xFE
TRAILS_PER_LEAD = LAST_TRAIL - FIRST_TRAIL + 1
ROW_COUNT = LAST_LEAD - FIRST_LEAD + 1
INDEX_SIZE = ROW_COUNT * TRAILS_PER_LEAD
EXPECTED_ENTRIES = 7445
VALUES_PER_LINE = 8
ENTRIES_PER_LINE = 4

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "src" / "detail" / "gb2312_table.c"


def collect() -> tuple[list[int], list[tuple[int, int]]]:
    """Return the flat index table and the code-point sorted entries."""
    index = [0] * INDEX_SIZE
    entries: list[tuple[int, int]] = []

    for lead in range(FIRST_LEAD, LAST_LEAD + 1):
        for trail in range(FIRST_TRAIL, LAST_TRAIL + 1):
            try:
                char = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            code_point = ord(char)
            index[(lead - FIRST_LEAD) * TRAILS_PER_LEAD + (trail - FIRST_TRAIL)] = code_point
            entries.append((code_point, (lead << 8) | trail))

    entries.sort()

    if len(entries) != EXPECTED_ENTRIES:
        raise SystemExit(
            f"unexpected entry count: {len(entries)} (expected {EXPECTED_ENTRIES})"
        )
    if len({cp for cp, _ in entries}) != len(entries):
        raise SystemExit("duplicate Unicode code points in the mapping")
    if len({code for _, code in entries}) != len(entries):
        raise SystemExit("duplicate GB2312 codes in the mapping")

    # Codes that belong to GBK or that some legacy tables map into the Private
    # Use Area must not appear in a GB2312 table.
    for forbidden in (0x20AC, 0x2170, 0xE810):
        if any(cp == forbidden for cp, _ in entries):
            raise SystemExit(f"U+{forbidden:04X} is not part of GB2312")

    return index, entries


def render(index: list[int], entries: list[tuple[int, int]]) -> str:
    payload = ",".join(f"{cp:04X}{code:04X}" for cp, code in entries)
    digest = hashlib.sha256(payload.encode("ascii")).hexdigest()

    lines = [
        "/*",
        " * gbcodec - GB2312 <-> Unicode conversion tables.",
        " *",
        " * Copyright (c) 2016-2026 leid",
        " * SPDX-License-Identifier: ISC",
        " *",
        " * Generated by tools/gen_gb2312_table.py from Python's gb2312 codec.",
        f" * Entries: {len(entries)} (6763 hanzi + 682 symbols)",
        f" * Mapping SHA-256: {digest}",
        " *",
        " * DO NOT EDIT: regenerate with `python3 tools/gen_gb2312_table.py`.",
        " */",
        '#include "gb2312_table.h"',
        "",
        "const uint16_t gbc_detail_gb2312_index[GBC_GB2312_INDEX_SIZE] = {",
    ]

    for row in range(ROW_COUNT):
        lead = FIRST_LEAD + row
        start = row * TRAILS_PER_LEAD
        chunk = index[start : start + TRAILS_PER_LEAD]
        lines.append(f"    /* 0x{lead:02X} */")
        for offset in range(0, len(chunk), VALUES_PER_LINE):
            values = ", ".join(f"0x{value:04X}" for value in chunk[offset : offset + VALUES_PER_LINE])
            lines.append(f"    {values},")

    lines.append("};")
    lines.append("")
    lines.append("const gbc_table_entry gbc_detail_code_point_order[GBC_TABLE_ENTRIES] = {")
    for offset in range(0, len(entries), ENTRIES_PER_LINE):
        chunk = entries[offset : offset + ENTRIES_PER_LINE]
        values = ", ".join(f"{{0x{cp:04X}, 0x{code:04X}}}" for cp, code in chunk)
        lines.append(f"    {values},")
    lines.append("};")
    lines.append("")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that the checked-in table matches the generator output",
    )
    args = parser.parse_args()

    index, entries = collect()
    content = render(index, entries)
    encoded = content.encode("utf-8")

    if args.check:
        if not args.output.is_file():
            print(f"error: {args.output} is missing", file=sys.stderr)
            return 1
        if args.output.read_bytes() != encoded:
            print(
                f"error: {args.output} is out of date; "
                "run `python3 tools/gen_gb2312_table.py`",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {args.output} is up to date ({len(entries)} entries)")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(content)
    print(f"wrote {args.output} ({len(entries)} entries, {len(encoded)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
